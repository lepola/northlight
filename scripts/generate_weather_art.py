"""Embed original camera frost and snow-floc alpha materials with complete L8 mip chains."""
from pathlib import Path
import hashlib
import random
from PIL import Image, ImageChops, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'shaders/assets'
OUTPUT = ROOT / 'src/generated/weather_texture_data.h'


def build():
    chunks = ['#pragma once\n// Generated by scripts/generate_weather_art.py; original materials, no game assets.\nnamespace NorthlightWeatherArt {\n']
    for symbol, name, size in [('Frost', 'camera-frost.png', (1024, 576)), ('Snow', 'snow-flocs.png', (512, 512)), ('Noise', None, (128, 128))]:
        if name:
            path = ASSETS / name
            with Image.open(path) as source:
                rgba = source.convert('RGBA')
                level = ImageChops.multiply(ImageOps.grayscale(rgba), rgba.getchannel('A')).resize(size, Image.Resampling.LANCZOS)
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
        else:
            level = Image.frombytes('L', size, random.Random(0x51a7).randbytes(size[0] * size[1]))
            digest = 'deterministic-value-noise-0x51a7'
        data = bytearray()
        while True:
            data.extend(level.tobytes())
            if level.size == (1, 1):
                break
            level = level.resize((max(1, level.width // 2), max(1, level.height // 2)), Image.Resampling.BOX)
        provenance = f'// source-sha256 {name} {digest}\n' if name else f'// Generator: {digest}\n'
        chunks += [provenance, f'inline constexpr unsigned k{symbol}Width={size[0]},k{symbol}Height={size[1]};\n',
                   f'inline constexpr unsigned char k{symbol}Texels[]={{\n']
        chunks += ['    ' + ','.join(str(value) for value in data[start:start + 32]) + ',\n' for start in range(0, len(data), 32)]
        chunks.append('};\n')
        print(name or 'value-noise', f'{size[0]}x{size[1]}', len(data), 'bytes including mips')
    chunks.append('}\n')
    contents = ''.join(chunks)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != contents:
        pending = OUTPUT.with_suffix('.h.tmp')
        pending.write_text(contents, encoding='utf-8', newline='\n')
        pending.replace(OUTPUT)


if __name__ == '__main__':
    build()
