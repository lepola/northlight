"""Embed the shipped regional overrides for settings reset, never the installed INIs."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
out = ['#pragma once', '// Generated by scripts/generate_settings_defaults.py.']
for name, filename in [('Celestial', 'celestial-profiles.ini'), ('ShadowRange', 'shadow-range-profiles.ini')]:
    text = (ROOT / 'client-config' / filename).read_text(encoding='utf-8')
    lines = [line.split('#', 1)[0].strip() for line in text.splitlines()]
    out.append('inline constexpr const char* kSettingsFactory' + name + ' = R"NL(' + '\n'.join(filter(None, lines)) + '\n)NL";')
(ROOT / 'src' / 'settings' / 'settings_defaults.h').parent.mkdir(exist_ok=True)
(ROOT / 'src' / 'settings' / 'settings_defaults.h').write_text('\n'.join(out) + '\n', encoding='utf-8')
