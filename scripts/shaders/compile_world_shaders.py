#!/usr/bin/env python3
"""Compile standalone HLSL with the pinned Microsoft compiler (shader_compiler.py).

Does not load WoW, a game DLL, or a graphics device. The generated header and
manifest are published only after every entry passes the Shader Model 3 gate.
--entries=WorldNormals,RemovalSmooth retains other verified binaries and their source hashes.
"""
from pathlib import Path
import hashlib
import json
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]  # repo root, scripts/shaders/
import northlight_paths as fp  # noqa: E402
from shader_compiler import Compiler, DLL_SHA256, COMPATIBLE_DLL_SHA256, bytecode, rows, validate_assembly

ENTRIES = (("WorldNormals", "ps_3_0"), ("WorldLighting", "ps_3_0"), ("ActorShadow", "ps_3_0"), ("ActorTiles", "ps_3_0"), ("WorldGI", "ps_3_0"), ("WorldFog", "ps_3_0"), ("FogBlur", "ps_3_0"), ("FogClouds", "ps_3_0"), ("FogTemporal", "ps_3_0"), ("LocalDirect", "ps_3_0"), ("LocalDirect16", "ps_3_0"), ("RemovalSmooth", "ps_3_0"), ("TemporalLight", "ps_3_0"), ("LocalFog", "ps_3_0"), ("LocalFogCombine", "ps_3_0"), ("SourceVisibilityPS", "ps_3_0"),
           ("WorldComposite", "ps_3_0"), ("MaterialComposite", "ps_3_0"), ("MaterialAudit", "ps_3_0"), ("ShadowVS", "vs_3_0"), ("ShadowCacheVS", "vs_3_0"),
           ("ShadowPS", "ps_3_0"), ("ShadowReplayPS", "ps_3_0"), ("ShadowUnion", "ps_3_0"))


def main():
    selected=next((a.split("=",1)[1].split(",") for a in sys.argv[1:] if a.startswith("--entries=")),None)
    if selected and not set(selected)<=set(e for e,_ in ENTRIES):raise SystemExit("Unknown entry")
    previous=json.loads((fp.SHADERS/"world-shader-build.json").read_text()) if selected else None
    compatible='--compatible-compiler' in sys.argv
    # Only the entries kept as they are must come from an accepted compiler; the top level is the fallback for entries without their own record.
    retained={s.get("compiler_sha256",previous["compiler_sha256"]) for e,s in previous["shaders"].items() if e not in selected} if previous else set()
    if not retained<=({DLL_SHA256,COMPATIBLE_DLL_SHA256} if compatible else {DLL_SHA256}):raise SystemExit("Retained shaders used another compiler: rebuild all entries")
    source=fp.SHADERS/"world_effects.hlsl"
    before=hashlib.sha256(source.read_bytes()).hexdigest()
    compiler=Compiler(allow_compatible_binary=compatible)
    header=["// Generated by compile_world_shaders.py; do not edit.","#pragma once","#include <windows.h>"]
    manifest={"bump_include_sha256":hashlib.sha256((fp.SHADERS/"auto_bump_normal.hlsl").read_bytes()).hexdigest(),"source_sha256":before,**compiler.provenance,"game_launched":False,"shaders":{}}
    for entry,target in ENTRIES:
        output=fp.COMPILED/f"{entry}.bin";asm=fp.COMPILED/f"{entry}.bin.asm"
        compile_entry=not selected or entry in selected
        if compile_entry:
            data,words=compiler.compile(source,entry,target,output)
        else:
            data,words=bytecode(output,target)
            if hashlib.sha256(data).hexdigest()!=previous["shaders"][entry]["sha256"]:
                raise ValueError(f"{entry}: retained bytecode differs from its previous manifest")
        stats=validate_assembly(asm,target)
        header.append(f"static const DWORD k{entry}Shader[] = {{\n"+"\n".join(rows(words))+"\n};")
        manifest["shaders"][entry]={"target":target,"bytes":len(data),"sha256":hashlib.sha256(data).hexdigest(),**stats,
            "compiler_sha256":compiler.provenance["compiler_sha256"] if compile_entry else previous["shaders"][entry].get("compiler_sha256",previous["compiler_sha256"]),
            "source_sha256":before if compile_entry else previous["shaders"][entry].get("source_sha256",previous["source_sha256"])}
        print(f"Validated {entry}: {stats['static_instruction_slots']} slots, {stats['temporary_registers']} temps",flush=True)
    if hashlib.sha256(source.read_bytes()).hexdigest()!=before:raise RuntimeError("HLSL changed while compiling")
    (fp.GENERATED/"world_compiled_shaders.h").write_text("\n\n".join(header)+"\n")
    (fp.SHADERS/"world-shader-build.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print("Published world_compiled_shaders.h and world-shader-build.json")

if __name__=="__main__":main()
