#!/usr/bin/env python3
"""Rebuild embedded shaders offline with the pinned Microsoft compiler (shader_compiler.py).

--entries=AO,AOContactBloom,AOBlur retains other verified bytecode.
No game DLL or rendering device is loaded.
"""
from pathlib import Path
import hashlib
import json
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]  # repo root, scripts/shaders/
import northlight_paths as fp  # noqa: E402
from shader_compiler import Compiler, DLL_SHA256, COMPATIBLE_DLL_SHA256, bytecode, rows, validate_assembly


def main():
    compatible = '--compatible-compiler' in sys.argv
    selected = next((a.split("=", 1)[1].split(",") for a in sys.argv[1:] if a.startswith("--entries=")), None)
    actor_names = {"AOActorPrepare", "HBAOActorContactBloom", "GTAOActorContactBloom", "HBAOActorOnly", "GTAOActorOnly"}
    names = actor_names | {"AO", "AOContactBloom", "HDAOContactBloom", "HBAOPlusContactBloom", "GTAOContactBloom", "ContactBloom", "AOBlur", "Composite", "RainMaskMRT", "RainScrub"}
    names |= {method + "ContactBloom" + quality for method in ("HDAO", "HBAOPlus", "GTAO") for quality in ("Medium", "Low")}
    if selected and not set(selected) <= names: raise SystemExit("Unknown shader entry")
    previous = json.loads((fp.SHADERS / "shader-build.json").read_text()) if selected else None
    actor_source = hashlib.sha256((fp.SHADERS / "effects.hlsl").read_bytes() + b"\n" + (fp.SHADERS / "ao_actor.hlsl").read_bytes()).hexdigest()
    if previous and previous.get('actor_source_sha256') != actor_source and not actor_names <= set(selected):
        raise SystemExit("Actor AO dependencies changed: include all five actor entries in --entries, or rebuild all shaders")
    if previous and previous.get("compiler_sha256") not in ({DLL_SHA256, COMPATIBLE_DLL_SHA256} if compatible else {DLL_SHA256}): raise SystemExit("Retained shaders used another compiler: rebuild all entries")
    compiler = Compiler(allow_compatible_binary=compatible)
    chunks = ["// Generated by compile_shaders.py; do not edit.\n#pragma once\n#include <windows.h>\n"]
    manifest = {"source_sha256": hashlib.sha256((fp.SHADERS / "effects.hlsl").read_bytes()).hexdigest(),
                "rain_source_sha256": hashlib.sha256((fp.SHADERS / "rain_mask.hlsl").read_bytes()).hexdigest(),
                "actor_source_sha256": actor_source,
                "target": "ps_3_0", **compiler.provenance, "game_launched": False, "shaders": {}}
    # 0.3.202 (rain mask MRT): the two rain mask pixel shaders are ps_2_0 (they pair with the game's fixed-function vertex pipeline and write
    # oC1); their manifest entries carry their own "target" and they compile from rain_mask.hlsl. The ps_3_0 entries are unchanged.
    for entry, symbol, target in (("AO", "kAoShader", "ps_3_0"), ("AOContactBloom", "kAoContactBloomShader", "ps_3_0"), ("ContactBloom", "kContactBloomShader", "ps_3_0"),
                                  ("HDAOContactBloom", "kHdaoContactBloomShader", "ps_3_0"), ("HBAOPlusContactBloom", "kHbaoPlusContactBloomShader", "ps_3_0"), ("GTAOContactBloom", "kGtaoContactBloomShader", "ps_3_0"),
                                  ("HDAOContactBloomMedium", "kHdaoContactBloomMediumShader", "ps_3_0"), ("HBAOPlusContactBloomMedium", "kHbaoPlusContactBloomMediumShader", "ps_3_0"), ("GTAOContactBloomMedium", "kGtaoContactBloomMediumShader", "ps_3_0"),
                                  ("HDAOContactBloomLow", "kHdaoContactBloomLowShader", "ps_3_0"), ("HBAOPlusContactBloomLow", "kHbaoPlusContactBloomLowShader", "ps_3_0"), ("GTAOContactBloomLow", "kGtaoContactBloomLowShader", "ps_3_0"),
                                  ("AOBlur", "kAoBlurShader", "ps_3_0"), ("Composite", "kCompositeShader", "ps_3_0"),
                                  ("AOActorPrepare", "kAoActorPrepareShader", "ps_3_0"), ("HBAOActorContactBloom", "kHbaoActorContactBloomShader", "ps_3_0"), ("GTAOActorContactBloom", "kGtaoActorContactBloomShader", "ps_3_0"),
                                  ("HBAOActorOnly", "kHbaoActorOnlyShader", "ps_3_0"), ("GTAOActorOnly", "kGtaoActorOnlyShader", "ps_3_0"),
                                  ("RainMaskMRT", "kRainMaskMrtShader", "ps_2_0"), ("RainScrub", "kRainScrubShader", "ps_2_0")):
        output = fp.COMPILED / f"{entry}.bin"
        legacy = target == "ps_3_0"
        source_key = "actor_source_sha256" if entry in actor_names else "source_sha256" if legacy else "rain_source_sha256"
        compile_entry = not selected or entry in selected or entry not in previous["shaders"]
        if compile_entry:
            data, words = compiler.compile(fp.SHADERS / ("ao_actor.hlsl" if entry in actor_names else "effects.hlsl" if legacy else "rain_mask.hlsl"), entry, target, output)
        else:
            data, words = bytecode(output, target)
            if hashlib.sha256(data).hexdigest() != previous["shaders"][entry]["sha256"]:
                raise ValueError(f"{entry}: retained bytecode differs from previous manifest")
        chunks.append(f"static const DWORD {symbol}[] = {{\n" + "\n".join(rows(words)) + "\n};\n")
        assembly = Path(f"{output}.asm")
        manifest["shaders"][entry] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                                      "compiler_sha256": compiler.provenance['compiler_sha256'] if compile_entry else previous['shaders'][entry].get('compiler_sha256', previous['compiler_sha256']),
                                      **({} if legacy else {"target": target}),
                                      **(validate_assembly(assembly, target) if legacy else validate_assembly(assembly, target, 96, 12)),
                                      "source_sha256": manifest[source_key] if compile_entry
                                      else previous["shaders"][entry].get("source_sha256", previous[source_key])}
    (fp.GENERATED / "compiled_shaders.h").write_text("\n".join(chunks), encoding="utf-8", newline="\n")
    (fp.SHADERS / "shader-build.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
