#!/usr/bin/env python3
"""Offline celestial HLSL compiler (shader_compiler.py); never launches a game/device."""
import hashlib,json,sys
from pathlib import Path
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]  # repo root, scripts/shaders/
import northlight_paths as fp  # noqa: E402
from shader_compiler import Compiler,rows,validate_assembly
def main():
    source=fp.SHADERS/'celestial_disc_effects.hlsl';digest=hashlib.sha256(source.read_bytes()).hexdigest()
    compiler=Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
    header=['// Generated by compile_celestial_disc_shaders.py','#pragma once','#include <windows.h>']
    shaders={}
    for entry in ('CelestialDiscPS','CelestialHaloVisibilityPS','CelestialVeilPS','CelestialTerrainVS','CelestialTerrainPS'):
        target='vs_3_0' if entry.endswith('VS') else 'ps_3_0'
        output=fp.COMPILED/(entry+'.bin');assembly=fp.COMPILED/(entry+'.bin.asm')
        data,words=compiler.compile(source,entry,target,output)
        stats=validate_assembly(assembly,target)
        if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:raise ValueError('Source changed during compile')
        header+=['static const DWORD k'+entry+'Shader[] = {']+rows(words)+['};']
        shaders[entry]={'target':target,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),**stats}
    (fp.GENERATED/'celestial_disc_compiled_shaders.h').write_text('\n'.join(header)+'\n',encoding='utf-8',newline='\n')
    report={'source_sha256':digest,**compiler.provenance,'game_launched':False,'device_created':False,'shader':shaders['CelestialDiscPS'],'shaders':shaders}
    (fp.SHADERS/'celestial-disc-shader-build.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8',newline='\n');print(json.dumps(report))
if __name__=='__main__':main()
