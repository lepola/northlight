#!/usr/bin/env python3
"""Offline SM3 compiler (shader_compiler.py) only; never creates a device or launches the game."""
import hashlib,json,re,sys
from pathlib import Path
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]  # repo root, scripts/shaders/
import northlight_paths as fp  # noqa: E402
from shader_compiler import Compiler,PROVENANCE,rows,validate_assembly

def main():
    source=fp.SHADERS/'local_light_effects.hlsl';digest=hashlib.sha256(source.read_bytes()).hexdigest()
    compiler=Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
    header=['// Generated by compile_local_light_shaders.py.','#pragma once','#include <windows.h>'];manifest={"bump_include_sha256":hashlib.sha256((fp.SHADERS/"auto_bump_normal.hlsl").read_bytes()).hexdigest(),'source_sha256':digest,**compiler.provenance,'game_launched':False,'device_created':False,'shaders':{}}
    for entry,target in [('LocalShadowVS','vs_3_0'),('LocalShadowPS','ps_3_0'),('LocalLighting','ps_3_0')]:
        output=fp.COMPILED/(entry+'.bin');assembly=fp.COMPILED/(entry+'.bin.asm')
        data,words=compiler.compile(source,entry,target,output)
        stats=validate_assembly(assembly,target)
        # The shared validator handles 2D entries. Cube texldl costs 5 slots,
        # versus 2 for 2D (Microsoft ps_3_0 instruction table, note 2).
        text=assembly.read_text();cube={int(x) for x in re.findall(r'dcl_cube\s+s(\d+)',text)}
        extra=0
        for line in text.splitlines():
            match=re.match(r'\s*(?:/\*.*?\*/|\d+:)?\s*(texldl|texldp|texld)\s+.*\bs(\d+)\b',line)
            if match and int(match[2]) in cube:extra+=1 if match[1]=='texldp' else 3
        stats['static_instruction_slots']+=extra;stats['cube_instruction_extra_slots']=extra
        if stats['static_instruction_slots']>512:raise ValueError('SM3 cube instruction slot limit exceeded')
        header.append('static const DWORD k%sShader[] = {\n%s\n};'%(entry,'\n'.join(rows(words))))
        manifest['shaders'][entry]={'target':target,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),**stats}
        print(entry,stats['static_instruction_slots'],'slots',stats['temporary_registers'],'temps',flush=True)
    if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:raise ValueError('Source changed during compilation')
    (fp.GENERATED/'local_light_compiled_shaders.h').write_text('\n\n'.join(header)+'\n')
    (fp.SHADERS/'local-light-shader-build.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':main()
