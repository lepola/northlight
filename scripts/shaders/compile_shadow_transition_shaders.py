#!/usr/bin/env python3
"""Compile optional direction-transition variants without rebuilding baseline entries."""
from pathlib import Path
import hashlib
import json
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]
import northlight_paths as fp
from shader_compiler import Compiler, rows, validate_assembly

ENTRIES = ("WorldLightingFade", "WorldFogFade", "FogCloudsFade")
SOURCES = ("world_effects.hlsl", "shadow_transition.hlsl")


def source_hashes():
    return {name: hashlib.sha256((fp.SHADERS / name).read_bytes()).hexdigest() for name in SOURCES}


def main():
    before = source_hashes()
    compiler = Compiler(allow_compatible_binary="--compatible-compiler" in sys.argv)
    header = ["// Generated by compile_shadow_transition_shaders.py; do not edit.", "#pragma once", "#include <windows.h>"]
    manifest = {"sources": before, **compiler.provenance, "game_launched": False, "shaders": {}}
    for entry in ENTRIES:
        output = fp.COMPILED / f"{entry}.bin"
        data, words = compiler.compile(fp.SHADERS / SOURCES[1], entry, "ps_3_0", output)
        stats = validate_assembly(Path(f"{output}.asm"), "ps_3_0")
        header.append(f"static const DWORD k{entry}Shader[] = {{\n" + "\n".join(rows(words)) + "\n};")
        manifest["shaders"][entry] = {"target": "ps_3_0", "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), **stats}
        print(f"Validated {entry}: {stats['static_instruction_slots']} slots, {stats['temporary_registers']} temps", flush=True)
    if source_hashes() != before:
        raise RuntimeError("HLSL changed while compiling")
    (fp.GENERATED / "shadow_transition_compiled_shaders.h").write_text("\n\n".join(header) + "\n", encoding="utf-8", newline="\n")
    (fp.SHADERS / "shadow-transition-shader-build.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
