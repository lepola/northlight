"""The one offline HLSL toolchain: Microsoft d3dcompiler_47 10.0.17134.12 (x64), IEEE strict.

compile_shaders.cpp runs under Wine on macOS (natively on Windows) next to a pinned copy of
Microsoft's redistributable DLL; WINEDLLOVERRIDES and the tool's own module check make Wine's
builtin d3dcompiler_47 impossible. The DLL is not in git: put it in
<tools>/d3dcompiler_47-10.0.17134.12-x64/ (northlight.local.ini [paths] tools).
Never loads WoW, a game DLL or a graphics device.
"""
from pathlib import Path
import hashlib
import os
import re
import shutil
import struct
import subprocess
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parents[1])]  # repo root, scripts/
import northlight_paths as fp  # noqa: E402

HERE = Path(__file__).resolve().parent   # compile_shaders.cpp
DLL_SHA256 = "3c5f066a121a446e55db9c699b392da5d3aca6ad9019437b722360d09698e3c3"
COMPATIBLE_DLL_SHA256 = "4432bbd1a390874f3f0a503d45cc48d346abc3a8c0213c289f4b615bf0ee84f3"
# D3DCOMPILE_ENABLE_BACKWARDS_COMPATIBILITY | D3DCOMPILE_IEEE_STRICTNESS | D3DCOMPILE_OPTIMIZATION_LEVEL3
COMPILER = "Microsoft d3dcompiler_47 10.0.17134.12 IEEE strict"
PROVENANCE = {"compiler": COMPILER, "compiler_sha256": DLL_SHA256}


def __getattr__(name):
    if name == 'DLL':
        return fp.tools() / 'd3dcompiler_47-10.0.17134.12-x64/d3dcompiler_47.dll'
    raise AttributeError(name)


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


class Compiler:
    """Builds compile_shaders.exe beside a verified copy of the DLL in out/shader-compiler/."""

    def __init__(self, allow_compatible_binary=False):
        from build_environment import wine_build_prefix, zig_env, TOOLS, ZIG
        DLL = TOOLS / 'd3dcompiler_47-10.0.17134.12-x64/d3dcompiler_47.dll'
        if not DLL.is_file():
            raise SystemExit(f"Microsoft d3dcompiler_47.dll 10.0.17134.12 (x64) missing: expected {DLL}")
        actual_hash = sha256(DLL)
        # A second signed distribution of the same Microsoft version. The native
        # helper independently verifies the PE/version and exact loaded path.
        if actual_hash != DLL_SHA256 and not (allow_compatible_binary and actual_hash == COMPATIBLE_DLL_SHA256):
            raise SystemExit(f"{DLL}: SHA-256 {sha256(DLL)} is not the pinned {DLL_SHA256}")
        self.provenance = {**PROVENANCE, 'compiler_sha256': actual_hash}
        self.dir = fp.out() / "shader-compiler"
        self.dir.mkdir(parents=True, exist_ok=True)
        self.exe = self.dir / "compile_shaders.exe"
        self.env = zig_env()
        subprocess.run([str(ZIG), "c++", "-target", "x86_64-windows-gnu", "-O2", "-s", "-static",
                        str(HERE / "compile_shaders.cpp"), "-o", str(self.exe)], env=self.env, check=True)
        local = self.dir / "d3dcompiler_47.dll"
        shutil.copyfile(DLL, local)
        if sha256(local) != actual_hash:
            raise RuntimeError(f"{local}: copy does not match the pinned SHA-256")
        self.command = [str(self.exe)]
        if os.name != "nt":
            from build_environment import WINE_ROOT
            self.env.update(WINEPREFIX=str(wine_build_prefix()), WINEDEBUG="-all", WINEDLLOVERRIDES="d3dcompiler_47=n",
                            DYLD_LIBRARY_PATH=str(WINE_ROOT / "lib/external"))
            self.command.insert(0, str(WINE_ROOT / "bin/wine"))

    def compile(self, source, entry, target, output):
        """Writes output and output.asm, then returns the bytecode checked for SM version and END."""
        asm = Path(f"{output}.asm")
        asm.unlink(missing_ok=True)
        subprocess.run([*self.command, str(source), entry, target, str(output)], env=self.env, check=True, timeout=120)
        if not asm.read_text().startswith("//\n// Generated by Microsoft (R) HLSL Shader Compiler 10.1\n"):
            raise RuntimeError(f"{asm.name}: not disassembled by Microsoft's compiler")
        return bytecode(output, target)


def bytecode(path, target):
    data = Path(path).read_bytes()
    if len(data) % 4: raise ValueError(f"{Path(path).name}: non-DWORD size")
    words = struct.unpack(f"<{len(data)//4}I", data)
    major, minor = target[3], target[5]
    expected = (0xfffe0000 if target.startswith("vs") else 0xffff0000) | int(major) << 8 | int(minor)
    if words[0] != expected or words[-1] != 0xffff: raise ValueError(f"{Path(path).name}: invalid {target} bytecode markers")
    return data, words


def rows(words):
    return ["    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + "," for i in range(0, len(words), 8)]


def instructions(path):
    """D3DDisassemble text without comments, blank lines and the /* n */ or n: instruction numbers."""
    lines = (re.sub(r"^(?:/\*.*?\*/|\d+:)\s*", "", line.split("//", 1)[0].strip()) for line in Path(path).read_text().rstrip("\0").splitlines())
    return [line for line in lines if line]


def validate_assembly(path, target, slot_limit=512, register_limit=32):
    """Baseline SM3 (or ps_2_0 with smaller limits) instruction slots and register limits.

    Cost references: Microsoft dx9-graphics-reference-asm-{ps,vs}-instructions-
    {ps,vs}-3-0. Only 2D texture instructions are costed here; compile_local_light_shaders.py
    adds the cube surcharge. A break_ne/lt/gt with identical operands can never exit its loop.
    """
    assembly = path.read_text().rstrip("\0")
    costs = dict.fromkeys("abs add break cmp dp3 dp4 else endif exp expp frc log logp mad max min mov mova mul nop rcp ret rsq setp sge slt sub texld".split(), 1)
    costs.update(dict.fromkeys("call crs dp2add dsx dsy endloop endrep lrp m3x2 texkill texldl".split(), 2))
    costs.update(dict.fromkeys("breakp callnz if ifc loop m3x3 m4x3 nrm pow rep texldd texldp lit sgn".split(), 3))
    costs.update(m3x4=4, m4x4=4, texldb=6, sincos=8)
    slots = 0; counts = {}
    for line in instructions(path):
        tokens = line.split()
        if tokens[0] in {"break_ne", "break_lt", "break_gt"}:
            operands = [s.strip() for s in line[len(tokens[0]):].split(",")]
            if len(operands) == 2 and operands[0] == operands[1]:
                raise ValueError(f"{path.name}: non-exiting loop branch: {line}")
        op = tokens[0].split("_")[0]
        if op in {"ps", "vs", "def", "defi", "defb", "dcl", "label"}: continue
        if op not in costs: raise ValueError(f"{path.name}: unknown opcode {tokens[0]}")
        slots += 3 if op == "break" and "_" in tokens[0] else costs[op]
        counts[op] = counts.get(op, 0) + 1
    if slots > slot_limit: raise ValueError(f"{path.name}: {slots} static slots exceeds {target} {slot_limit}")
    temps = [int(n) for n in re.findall(r"\br(\d+)\b", assembly)]
    if max(temps, default=-1) >= register_limit: raise ValueError(f"{path.name}: temporary register limit")
    samplers = sorted({int(n) for n in re.findall(r"\bs(\d+)\b", assembly)})
    if samplers and max(samplers) >= (4 if target.startswith("vs") else 16):
        raise ValueError(f"{path.name}: sampler register limit")
    return {"static_instruction_slots": slots, "temporary_registers": max(temps, default=-1) + 1,
            "samplers": samplers, "instructions": counts}
