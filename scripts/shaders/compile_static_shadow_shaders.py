#!/usr/bin/env python3
"""Compile standalone HLSL with the pinned Microsoft compiler (shader_compiler.py).

Does not load WoW, a game DLL, or a graphics device. The generated header and
manifest are published only after every entry passes the Shader Model 3 gate.
"""
from pathlib import Path
import hashlib
import json
import re
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]  # repo root, scripts/shaders/
import northlight_paths as fp  # noqa: E402
from shader_compiler import Compiler, rows, validate_assembly

ENTRIES = (("StaticCasterVS", "vs_3_0"), ("StaticCasterInstancedVS", "vs_3_0"), ("StaticCasterPS", "ps_3_0"), ("StaticCasterFastPS", "ps_3_0"), ("StaticCasterOpaqueFastPS", "ps_3_0"), ("StaticCasterOpaquePS", "ps_3_0"))


def main():
    source=fp.SHADERS/"static_shadow_effects.hlsl"
    before=hashlib.sha256(source.read_bytes()).hexdigest()
    compiler=Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
    header=["// Generated by compile_static_shadow_shaders.py; do not edit.","#pragma once","#include <windows.h>"]
    manifest={"source_sha256":before,**compiler.provenance,"game_launched":False,"shaders":{}}
    for entry,target in ENTRIES:
        output=fp.COMPILED/f"{entry}.bin";asm=fp.COMPILED/f"{entry}.bin.asm"
        data,words=compiler.compile(source,entry,target,output)
        stats=validate_assembly(asm,target)
        assembly=asm.read_text()
        if entry in ("StaticCasterFastPS", "StaticCasterOpaqueFastPS") and re.search(r"\boDepth\b",assembly,re.I):
            raise ValueError(f"{entry}: fast path must not emit DEPTH")
        if entry in ("StaticCasterOpaquePS", "StaticCasterOpaqueFastPS") and stats["samplers"]:
            raise ValueError(f"{entry}: opaque path must not sample textures")
        header.append(f"static const DWORD k{entry}Shader[] = {{\n"+"\n".join(rows(words))+"\n};")
        manifest["shaders"][entry]={"target":target,"bytes":len(data),
            "sha256":hashlib.sha256(data).hexdigest(),**stats}
        print(f"Validated {entry}: {stats['static_instruction_slots']} slots, {stats['temporary_registers']} temps",flush=True)
    if hashlib.sha256(source.read_bytes()).hexdigest()!=before:raise RuntimeError("HLSL changed while compiling")
    (fp.GENERATED/"static_shadow_compiled_shaders.h").write_text("\n\n".join(header)+"\n")
    (fp.SHADERS/"static-shadow-shader-build.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print("Published static_shadow_compiled_shaders.h and static-shadow-shader-build.json")

if __name__=="__main__":main()
