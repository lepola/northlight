"""Offline SM3 compilation of Northlight precipitation; never loads a game or D3D device."""
from pathlib import Path
import hashlib
import json
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]
import northlight_paths as fp
from shader_compiler import Compiler, rows, validate_assembly

compiler = Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
source = fp.SHADERS / 'surface_effects.hlsl'
entries = ('PrecipitationQuality', 'PrecipitationPerformance')
manifest = {'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'target': 'ps_3_0',
            **compiler.provenance, 'game_launched': False, 'shaders': {}}
chunks = ['#pragma once\n#include <windows.h>\n// Generated by scripts/shaders/compile_surface_shaders.py.\n']
for entry in entries:
    output = fp.COMPILED / (entry + '.bin')
    data, words = compiler.compile(source, entry, 'ps_3_0', output)
    manifest['shaders'][entry] = {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
                                **validate_assembly(Path(str(output) + '.asm'), 'ps_3_0')}
    chunks.append('static const DWORD k' + entry + 'Shader[] = {\n' + '\n'.join(rows(words)) + '\n};\n')
fp.src('compiled_shaders.h').with_name('surface_compiled_shaders.h').write_text('\n'.join(chunks), encoding='utf-8')
(fp.SHADERS / 'surface-shader-build.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
print('Compiled', ', '.join(entries))
