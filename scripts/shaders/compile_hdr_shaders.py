"""Compile the native HDR transfer shaders; never loads a renderer or game."""
import hashlib
import json
from pathlib import Path
import sys

sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parents[1])]
import northlight_paths as fp
import shader_compiler as shared
from shader_compiler import validate_assembly

# The installed Windows build uses this official SDK 17134.12 binary.
# Limit the adapter to this exact file; retain the upstream toolchain's default pin.
SDK_SHA256 = '4432bbd1a390874f3f0a503d45cc48d346abc3a8c0213c289f4b615bf0ee84f3'

def hdr_compiler(compatible=False):
    return shared.Compiler(allow_compatible_binary=compatible)

def main():
    compiler = hdr_compiler('--compatible-compiler' in sys.argv)
    source = fp.SHADERS / 'hdr_effects.hlsl'
    result = {'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
              **compiler.provenance, 'game_launched': False, 'shaders': {}}
    chunks = ['// Generated by compile_hdr_shaders.py.\n#pragma once\n#include <cstdint>\n']
    entries = [('HdrUi', 'ps_2_0', 'HdrUi-ps_2_0', 'kHdrUiPs2'),
               ('HdrUi', 'ps_3_0', 'HdrUi-ps_3_0', 'kHdrUiPs3'),
               ('HdrWorld', 'ps_3_0', 'HdrWorld', 'kHdrWorld')]
    for entry, target, name, symbol in entries:
        binary = fp.COMPILED / (name + '.bin')
        data, words = compiler.compile(source, entry, target, binary)
        info = validate_assembly(binary.with_suffix('.bin.asm'), target, 64 if target == 'ps_2_0' else 512, 12 if target == 'ps_2_0' else 32)
        chunks.append('static constexpr std::uint32_t %s[]={\n' % symbol)
        chunks.extend('    ' + ','.join('0x%08x' % w for w in words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
        chunks.append('};\n')
        result['shaders'][name] = dict(info, target=target, sha256=hashlib.sha256(data).hexdigest(), bytes=len(data))
    (fp.GENERATED/'hdr_compiled_shaders.h').write_text(''.join(chunks), encoding='utf-8', newline='\n')
    (fp.SHADERS/'hdr-shader-build.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8', newline='\n')

if __name__ == '__main__':
    main()
