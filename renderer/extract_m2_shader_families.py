#!/usr/bin/env python3
"""Write src/gamedata/m2_shader_families.h: the M2 vertex shaders by family, keyed by bytecode identity.

No game execution. Each listed vertex shader is read from every archive of the client's chain that
holds it (union of nonempty variants, no claim about archive priority, as extract_signatures.py does) in every
shader model; hashes are FNV-1a-64 over the complete D3D token stream (version token through END, the BLS
container excluded), which is what Device::CreateVertexShader hashes at run time. Several --client folders
give the union of their tables. arbvp1/nvvp programs are not D3D bytecode and are not read.

    python3 renderer/extract_m2_shader_families.py [--client DIR ...] [--output FILE]
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import northlight_paths  # noqa: E402
import client_archives  # noqa: E402
from mpq import Archive  # noqa: E402
from extract_signatures import variants, fnv1a64  # noqa: E402

PARTICLE, PARTICLE_UNLIT, MODEL, PROJECTED, RIPPLES = 1, 2, 3, 4, 5
FAMILIES = {
    'Particle': (PARTICLE, ('CDiffuse_T1',)),
    'ParticleUnlit': (PARTICLE_UNLIT, ('Color_T1',)),
    'Model': (MODEL, ('Diffuse_T1', 'Diffuse_T2', 'Diffuse_T1_T2', 'Diffuse_Env', 'Diffuse_T1_Env',
                      'Diffuse_Env_T2', 'Diffuse_Env_Env')),
    'Projected': (PROJECTED, ('Diffuse_Proj_Proj', 'Color_Proj_Proj')),
    'Ripples': (RIPPLES, ('WaterRipples',)),
}
# Shaders the client does not ship in every D3D model (a missing model is not an error as long as one model has them).
SOME_MODELS = {'WaterRipples'}
# Byte-identical programs the game ships under two particle shaders (vs_1_1 CDiffuse_T1 and Color_T1) cannot be told
# apart by identity: they map to the first family. Any other overlap between families fails.
SHARED = {frozenset(('Particle', 'ParticleUnlit')): 'Particle'}
D3D_MODELS = ('vs_1_1', 'vs_2_0', 'vs_3_0')
MODEL_DIR = re.compile(r'^shaders\\vertex\\(vs_[123]_\d+)\\', re.I)


def models_of(archives):
    """Shader models to read: the D3D ones the game ships, plus any other vs_1..3 folder a listfile shows."""
    found = set(D3D_MODELS)
    for archive in archives:
        try:
            for name in archive.names():
                match = MODEL_DIR.match(name)
                if match:
                    found.add(match.group(1).lower())
        except (OSError, ValueError):
            pass
    return sorted(found)


def merge(a, b, value):
    if a == b:
        return a
    try:
        return SHARED[frozenset((a, b))]
    except KeyError:
        raise ValueError(f'hash {value:016x} is in both {a} and {b}') from None


def collect(client):
    """{hash: (family name, bytecode)} and the variant rows [(family, shader, model, count)] of one client."""
    paths = client_archives.chain(client, 'all')
    archives = [Archive(p) for p in paths]
    try:
        records, rows, found = {}, [], set()
        for family, (_, shaders) in FAMILIES.items():
            for shader in shaders:
                for model in models_of(archives):
                    name = f'shaders\\vertex\\{model}\\{shader}.bls'
                    count, seen = 0, False
                    for archive in archives:
                        if not archive.has(name):
                            continue
                        for _, _, code in variants(archive.read(name)):
                            seen = True
                            count += 1
                            value = fnv1a64(code)
                            old = records.get(value)
                            if old is not None and old[1] != code:
                                raise ValueError('FNV64 collision')
                            records[value] = (merge(old[0], family, value) if old else family, code)
                    if seen:
                        rows.append((family, shader, model, count))
                        found.add(shader)
                    elif model in D3D_MODELS and shader not in SOME_MODELS:
                        raise ValueError(f'{name}: no nonempty variant in any archive of the client')
        for shader in SOME_MODELS - found:
            raise ValueError(f'{shader}: no nonempty variant in any model or archive of the client')
        return records, rows
    finally:
        for archive in archives:
            archive.close()


def render(records, sources):
    header = ['// Generated by renderer/extract_m2_shader_families.py; do not edit. Exact original bytecode identities',
              '// (FNV-1a64 over the complete D3D token stream, version token through END, as Device::CreateVertexShader',
              '// hashes it) of the M2 vertex shaders, by family. Union of every nonempty variant in all enabled archives',
              f'// of {sources}; no claim about archive priority. Hashes only, no shader bytes.',
              '#pragma once', '#include <cstddef>', '#include <cstdint>',
              'struct M2ShaderFamilySignature { std::uint64_t hash; unsigned family; };',
              '// 1 Particle (CDiffuse_T1), 2 ParticleUnlit (Color_T1), 3 Model (Diffuse_T1 ... Diffuse_Env_Env),',
              '// 4 Projected (Diffuse_Proj_Proj, Color_Proj_Proj), 5 Ripples (WaterRipples: not an M2 shader, the water ripple draws, which the spell layer',
              '// treats like water). 0 = none of these. The vs_1_1 programs shared byte for byte by CDiffuse_T1 and Color_T1 are listed as 1',
              '// (identity cannot tell them apart).',
              'namespace NorthlightM2Family { constexpr unsigned kNone = 0, kParticle = 1, kParticleUnlit = 2, kModel = 3, kProjected = 4, kRipples = 5; }',
              'static constexpr M2ShaderFamilySignature kM2ShaderFamilies[] = {']
    for value, (family, _) in sorted(records.items()):
        header.append('    {UINT64_C(0x%016x), %d},' % (value, FAMILIES[family][0]))
    header += ['};',
               'static constexpr std::size_t kM2ShaderFamilyCount = sizeof(kM2ShaderFamilies) / sizeof(kM2ShaderFamilies[0]);',
               'constexpr unsigned m2ShaderFamily(std::uint64_t hash) {',
               '    std::size_t low = 0, high = kM2ShaderFamilyCount;',
               '    while (low < high) { const std::size_t middle = (low + high) / 2; if (kM2ShaderFamilies[middle].hash < hash) low = middle + 1; else high = middle; }',
               '    return low < kM2ShaderFamilyCount && kM2ShaderFamilies[low].hash == hash ? kM2ShaderFamilies[low].family : 0u;',
               '}']
    return '\n'.join(header) + '\n'


def generate(clients):
    """(header text, summary lines) for the union of the clients' tables."""
    merged, rows = {}, []
    for client in clients:
        records, client_rows = collect(client)
        for value, (family, code) in records.items():
            old = merged.get(value)
            merged[value] = (merge(old[0], family, value) if old else family, code)
        rows += client_rows
    sources = 'the configured client' if len(clients) == 1 else f'{len(clients)} clients (their union)'
    lines = []
    for family in FAMILIES:
        mine = [r for r in rows if r[0] == family]
        unique = sum(v[0] == family for v in merged.values())
        lines.append(f'{family}: {sum(r[3] for r in mine)} variants read, {unique} unique hashes, models '
                     + ','.join(sorted({r[2] for r in mine})))
    return render(merged, sources), lines, set(merged)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--client', action='append', help='client folder (repeatable; default: the configured client)')
    parser.add_argument('--output', help='header to write (default: src/gamedata/m2_shader_families.h)')
    args = parser.parse_args()
    clients = [Path(c) for c in args.client] if args.client else [northlight_paths.client_root()]
    text, lines, _ = generate(clients)
    out = Path(args.output) if args.output else northlight_paths.GAMEDATA / 'm2_shader_families.h'
    out.write_text(text, newline="\n")
    print('\n'.join(lines))
    print('Wrote', out.name if not args.output else args.output)


if __name__ == '__main__':
    main()
